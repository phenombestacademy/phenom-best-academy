create or replace function public.parent_child_summary()
returns table(
  child_id uuid,
  full_name text,
  account_type text,
  friend_count bigint,
  message_count bigint,
  flagged_count bigint,
  open_safety_alerts bigint,
  service_enquiries bigint,
  active_subscriptions bigint
)
language sql stable security definer set search_path=public as $$
  select p.id, p.full_name, p.account_type,
    (select count(*) from public.friend_requests f where (f.requester_id=p.id or f.recipient_id=p.id) and f.status='accepted'),
    (select count(*) from public.messages m where m.sender_id=p.id),
    (select count(*) from public.messages m where m.sender_id=p.id and m.moderation_status in ('flagged','blocked','removed')),
    (select count(*) from public.safety_alerts a where a.user_id=p.id and a.status in ('open','reviewing')),
    (select count(*) from public.service_enquiries e where e.user_id=p.id and e.status not in ('closed')),
    (select count(*) from public.subscriptions s where s.user_id=p.id and s.status='active')
  from public.profiles p
  where public.is_parent_of(p.id);
$$;
revoke all on function public.parent_child_summary() from public;
grant execute on function public.parent_child_summary() to authenticated;

