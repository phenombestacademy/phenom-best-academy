-- Prevent a second attempt number from overwriting an earlier attempt.
create or replace function public.enforce_attempt_sequence()
returns trigger language plpgsql as $$
begin
  if new.attempt_no < 1 then raise exception 'Attempt number must be at least 1'; end if;
  if new.submitted_at is not null and exists (
    select 1 from public.quiz_attempts q
    where q.quiz_id=new.quiz_id and q.student_id=new.student_id and q.attempt_no=new.attempt_no and q.id<>coalesce(new.id,gen_random_uuid())
  ) then raise exception 'This attempt number already exists'; end if;
  return new;
end; $$;

