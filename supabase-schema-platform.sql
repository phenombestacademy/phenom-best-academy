create or replace function public.is_staff()
returns boolean language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.profiles where id=auth.uid() and role in ('staff','admin','super_admin'));
$$;

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.profiles where id=auth.uid() and role in ('admin','super_admin'));
$$;

create or replace function public.is_super_admin()
returns boolean language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.profiles where id=auth.uid() and role='super_admin');
$$;

create or replace function public.is_parent_of(child uuid)
returns boolean language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.parent_links where parent_id=auth.uid() and child_id=child and status='active');
$$;

