-- Helper: current user's membership in a school.
create or replace function public.is_school_member(p_school uuid, p_roles text[] default null)
returns boolean language sql stable security definer set search_path=public as $$
  select exists (
    select 1 from public.school_members sm
    where sm.school_id=p_school and sm.user_id=auth.uid() and sm.status='active'
      and (p_roles is null or sm.role = any(p_roles))
  );
$$;

-- Higher Academy roles can oversee all school tenants; school roles stay tenant-bound.
